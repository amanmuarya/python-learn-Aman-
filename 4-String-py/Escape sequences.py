# Escape Sequences in Python

# Escape sequences Python mein special character combinations hote hain jo strings ke andar special formatting ya characters represent karne ke liye use hote hain.

# \n — New Line
print("Hello\nAman")


# 2. \t — Tab
print("Name:\tAman")

# 3. \" — Double Quote
print("He said, \"Hello Aman\"")

# 4. \\ — Backslash
print("C:\\Users\\Aman")

# Easy Definition 🐍
# Escape sequences are special character combinations beginning with \ that are used to represent special characters or formatting inside Python strings.