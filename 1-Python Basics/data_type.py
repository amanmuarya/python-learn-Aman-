# Primitive Data Types in Python

# int (Integer)
# Stores whole numbers.

age = 20
marks = 95
print(age, marks)

# float (Floating-Point Number)
# Stores decimal numbers.
price = 99.99
height = 5.8
print( price, height)


# complex (Complex Number)
# Stores numbers with a real part and an imaginary part (j).

num1 = 2 + 3j
num2 = 5 - 4j
print(num1 , num2)

# bool (Boolean)
# Stores only True or False.
is_student = True
is_logged_in = False

# str (String)
# Stores text or characters.

name = "Aman"
language = "Python"

print(name, language)