# Escape Sequences in Python

# Escape sequences Python mein special character combinations hote hain jo strings ke andar special formatting ya characters represent karne ke liye use hote hain.

# 1. \n — New Line
print("Hello\nAman")

# 2. \t — Tab
print("Name:\tAman")

# 3. \" — Double Quote
print("He said, \"Hello Aman\"")

# 4. \\ — Backslash
print("C:\\Users\\Aman")

# example for all escape

print("My Name:\tAman")
print("My Course:\tB.Tech CSE")
print("College:\tSubharti")
print("He said, \"I am learning Python.\"")
print("File Path:\tC:\\Python\\project")
print("Line 1\nLine 2\nLine 3")